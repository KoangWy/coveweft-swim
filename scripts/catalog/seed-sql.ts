import { compareText } from "./csv.ts";
import type { CatalogData } from "./types.ts";

type FlatVariant = {
  sku: string;
  variantSku: string;
  optionLabel: string;
  sizeGuideKey: string | null;
  stock: number;
  position: number;
};

/**
 * Renders the catalog seed as SQL. The file is generated from the committed
 * JSON so `supabase db reset` can load the catalog without a Node process.
 *
 * Every insert uses `ON CONFLICT DO NOTHING`: a reset starts from an empty
 * database, while a re-run keeps existing stock and administrator edits.
 */
export function renderSeedSql(data: CatalogData): string {
  const variants = flattenVariants(data);
  const productTranslations = Object.entries(data.translations.products)
    .map(([sku, translation]) => ({
      sku,
      description: translation.description,
      caption: translation.caption,
    }))
    .sort((left, right) => compareText(left.sku, right.sku));

  const attributeTranslations = Object.entries(data.translations.attributes)
    .flatMap(([attribute, values]) =>
      Object.entries(values).map(([value, label]) => ({ attribute, value, label })),
    )
    .sort(
      (left, right) =>
        compareText(left.attribute, right.attribute) || compareText(left.value, right.value),
    );

  return [
    "-- Catalog seed for COVEWEFT Swim.",
    "--",
    "-- Generated by `pnpm catalog:export`; do not edit by hand.",
    "--",
    "-- This file runs as the database owner during `supabase db reset`, so it can",
    "-- insert the initial variant stock directly. `pnpm db:seed` loads the same rows",
    "-- through the service role, which keeps the table privileges that the RLS",
    "-- migration reserves for trusted provisioning. Client roles never receive an",
    "-- INSERT grant on `product_variants.stock`; later stock changes go through",
    "-- `admin_adjust_stock` and are audited.",
    "--",
    "-- Every statement is idempotent: existing products, variants, images, and",
    "-- translations are left unchanged, so admin edits and stock survive a re-run.",
    "--",
    `-- Rows: ${data.products.length} products, ${variants.length} variants, ${data.images.length} images,`,
    `-- ${productTranslations.length} product translations, ${attributeTranslations.length} attribute translations.`,
    "",
    "insert into public.store_settings (id)",
    "values (1)",
    "on conflict (id) do nothing;",
    "",
    "insert into public.products (",
    "  sku, article_id, name, product_type, category, gender, collection, color,",
    "  color_family, pattern, material, fabric_desc, sleeve, neckline, fit, length,",
    "  closure, lining, features, season, brand, price_vnd, description, caption, is_active",
    ")",
    "select",
    "  item ->> 'sku',",
    "  nullif(item ->> 'articleId', ''),",
    "  item ->> 'name',",
    "  item ->> 'productType',",
    "  item ->> 'category',",
    "  item ->> 'gender',",
    "  nullif(item ->> 'collection', ''),",
    "  nullif(item ->> 'color', ''),",
    "  nullif(item ->> 'colorFamily', ''),",
    "  nullif(item ->> 'pattern', ''),",
    "  nullif(item ->> 'material', ''),",
    "  nullif(item ->> 'fabricDesc', ''),",
    "  nullif(item ->> 'sleeve', ''),",
    "  nullif(item ->> 'neckline', ''),",
    "  nullif(item ->> 'fit', ''),",
    "  nullif(item ->> 'length', ''),",
    "  nullif(item ->> 'closure', ''),",
    "  nullif(item ->> 'lining', ''),",
    "  array(select jsonb_array_elements_text(item -> 'features')),",
    "  nullif(item ->> 'season', ''),",
    "  nullif(item ->> 'brand', ''),",
    "  (item ->> 'priceVnd')::integer,",
    "  item ->> 'description',",
    "  item ->> 'caption',",
    "  (item ->> 'isActive')::boolean",
    `from jsonb_array_elements($catalog_products$${json(data.products)}$catalog_products$::jsonb) as item`,
    "on conflict (sku) do nothing;",
    "",
    "insert into public.product_variants (",
    "  product_id, variant_sku, option_label, size_guide_key, stock, position",
    ")",
    "select",
    "  product.id,",
    "  item ->> 'variantSku',",
    "  item ->> 'optionLabel',",
    "  nullif(item ->> 'sizeGuideKey', ''),",
    "  (item ->> 'stock')::integer,",
    "  (item ->> 'position')::integer",
    `from jsonb_array_elements($catalog_variants$${json(variants)}$catalog_variants$::jsonb) as item`,
    "join public.products as product on product.sku = (item ->> 'sku')",
    "on conflict (variant_sku) do nothing;",
    "",
    "insert into public.product_images (",
    "  product_id, kind, source, path, position, drive_file_id",
    ")",
    "select",
    "  product.id,",
    "  'studio',",
    "  'release',",
    "  item ->> 'path',",
    "  (item ->> 'position')::integer,",
    "  item ->> 'driveFileId'",
    `from jsonb_array_elements($catalog_images$${json(data.images)}$catalog_images$::jsonb) as item`,
    "join public.products as product on product.sku = (item ->> 'sku')",
    "on conflict (product_id, kind, source, path) do nothing;",
    "",
    "insert into public.product_translations (product_id, locale, description, caption)",
    "select",
    "  product.id,",
    "  'vi',",
    "  item ->> 'description',",
    "  item ->> 'caption'",
    `from jsonb_array_elements($catalog_product_translations$${json(productTranslations)}$catalog_product_translations$::jsonb) as item`,
    "join public.products as product on product.sku = (item ->> 'sku')",
    "on conflict (product_id, locale) do nothing;",
    "",
    "insert into public.attribute_translations (attribute, value, locale, label)",
    "select",
    "  item ->> 'attribute',",
    "  item ->> 'value',",
    "  'vi',",
    "  item ->> 'label'",
    `from jsonb_array_elements($catalog_attribute_translations$${json(attributeTranslations)}$catalog_attribute_translations$::jsonb) as item`,
    "on conflict (attribute, value, locale) do nothing;",
    "",
  ].join("\n");
}

function flattenVariants(data: CatalogData): FlatVariant[] {
  const variants: FlatVariant[] = [];

  for (const group of data.variants) {
    group.sizes.forEach((size, index) => {
      variants.push({
        sku: group.sku,
        variantSku: group.variantSkuBySize[size] ?? "",
        optionLabel: size,
        sizeGuideKey: group.sizeGuideKeyBySize[size] ?? null,
        stock: group.stockBySize[size] ?? 0,
        position: index + 1,
      });
    });
  }

  return variants;
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2);
}
